func Build(cfg *config.Config) string {
	shell := detectShell()

	var osPrompt string
	switch runtime.GOOS {
	case "windows":
		osPrompt = "Windows mode: prefer PowerShell-compatible commands."
	case "darwin":
		osPrompt = "macOS mode: use POSIX shell commands."
	default:
		osPrompt = "Linux mode: use POSIX shell commands."
	}

	parts := []string{
		Render("base", nil),
		"",
		"# Environment",
		fmt.Sprintf("- cwd: %s", cfg.Cwd),
		fmt.Sprintf("- platform: %s/%s", runtime.GOOS, runtime.GOARCH),
		fmt.Sprintf("- shell: %s", shell),
		"",
		"# OS Notes",
		osPrompt,
	}

	projectInstr := loadProjectInstructions(cfg.Cwd)
	if len(projectInstr) > 0 {
		parts = append(parts, "", "# Project Instructions")
		parts = append(parts, projectInstr...)
	}

	if visionLine := visionPromptLine(cfg); visionLine != "" {
		parts = append(parts, "", "# Vision", visionLine)
	}
	return strings.Join(parts, "\n")
}

// visionPromptLine advertises the active model's vision capability so the
// agent knows whether attached images actually reach it, and through whom.
func visionPromptLine(cfg *config.Config) string {
	if cfg == nil {
		return ""
	}
	model := strings.TrimSpace(cfg.Model)
	if model == "" {
		model = "the active model"
	}
	mainYes := cfg.VisionKnown && cfg.VisionAvailable
	mainNo := cfg.VisionKnown && !cfg.VisionAvailable
	sideYes := cfg.SidecarVisionAvailable
	sideName := strings.TrimSpace(cfg.SidecarModel)
	if sideName == "" {
		sideName = "the sidecar"
	}
	// A model explicitly bound to the vision role (/setmodel vision) wins
	// over the derived routes, so the prompt names it instead.
	visionName := strings.TrimSpace(cfg.RoleModelName(config.RoleVision))
	visionYes := visionName != ""
	switch {
	case mainYes:
		line := fmt.Sprintf("- Vision: AVAILABLE (%s sees images). Images the user sends you — pasted, dropped or attached, for example with /image — arrive as visual content in their message: answer about them directly, and do NOT call Read or DescribeImage on them, there is no file path to use. To look at an image file the user names or that you find on disk, use Read to attach it. Supported formats: %s.",
			model, "JPEG, PNG, GIF, BMP")
		switch {
		case visionYes:
			line += fmt.Sprintf(" For a second opinion on an image file, call DescribeImage on that file (answered by %s, the vision role).", visionName)
		case sideYes:
			line += fmt.Sprintf(" For a second opinion on an image file, call DescribeImage on that file (answered by %s).", sideName)
		default:
			line += " For a second opinion on an image file, call DescribeImage on that file."
		}
		return line
	case mainNo && visionYes:
		return fmt.Sprintf("- Vision: via VISION MODEL (%s cannot see images, but %s, bound to the vision role, can). Images you Read, and images the user sends, arrive as textual descriptions generated by %s — treat them as visual observations, not as your own sight. There is no file path to use for an image the user sent directly; do not try. For a closer look at an image file, call DescribeImage on that file.", model, visionName, visionName)
	case mainNo && sideYes:
		return fmt.Sprintf("- Vision: via SIDECAR (%s cannot see images, but %s can). Images you Read, and images the user sends, arrive as textual descriptions generated by the sidecar — treat them as visual observations, not as your own sight. There is no file path to use for an image the user sent directly; do not try. For a closer look at an image file, call DescribeImage on that file.", model, sideName)
	case mainNo:
		return fmt.Sprintf("- Vision: NOT available (%s has no vision capability). You cannot see images: do not claim otherwise. If the user asks about image content, explain the limitation briefly and suggest switching to a vision-capable model (e.g. llava, qwen2-vl, moondream) with /setmodel.",
			model)
	default:
		line := fmt.Sprintf("- Vision: UNKNOWN for %s (capability detection failed). Images the user sends arrive as visual content when the model supports it; answer about them directly and do not call Read or DescribeImage on them. You may try Read on an image file the user names; if the attach fails or you receive no visual content, say so honestly instead of guessing.",
			model)
		if visionYes {
			line += fmt.Sprintf(" Images can also be described by %s, the model bound to the vision role: call DescribeImage.", visionName)
		} else if sideYes {
			line += fmt.Sprintf(" If attaching fails, %s can still describe images: call DescribeImage.", sideName)
		}
		return line
	}
}

func detectShell() string {
	for _, key := range []string{"SHELL", "COMSPEC"} {
		if value := strings.TrimSpace(os.Getenv(key)); value != "" {
			return value
		}
	}
	return "unknown"
}

func loadProjectInstructions(cwd string) []string {
	start, err := filepath.Abs(cwd)
	if err != nil {
		return nil
	}
	entries := make([]string, 0, 8)
	current := start
	for i := 0; i < 10; i++ {
		for _, name := range []string{".vibe-coder.json", "AGENTS.md"} {
			path := filepath.Join(current, name)
			info, err := os.Lstat(path)
			if err != nil || info.Mode()&os.ModeSymlink != 0 {
				continue
			}
			data, err := os.ReadFile(path)
			if err != nil {
				continue
			}
			if len(data) > 4000 {
				data = data[:4000]
			}
			clean := SanitizeInstructions(string(data))
			rel, _ := filepath.Rel(start, path)
			entries = append(entries, fmt.Sprintf("From %s:\n%s", relPath(rel), clean))
		}
		parent := filepath.Dir(current)
		if parent == current {
			break
		}
		current = parent
	}
	return entries
}

func SanitizeInstructions(input string) string {
	out := input
	replacements := []*regexp.Regexp{
		regexp.MustCompile(`(?is)<invoke.*?>.*?</invoke>`),
		regexp.MustCompile(`(?is)<function=.*?>.*?</function>`),
		regexp.MustCompile(`(?is)<[A-Z_]+>.*?</[A-Z_]+>`),
	}
	for _, re := range replacements {
		out = re.ReplaceAllString(out, "[BLOCKED]")
	}
	return strings.TrimSpace(out)
}

func relPath(rel string) string {
	if rel == "" || rel == "." {
		return "."
	}
	return filepath.ToSlash(rel)
}
